"""Download offline Pokémon menu icons (Gen VII, 40x30) from PokeAPI for the journey species.
Party lists and menus use these instead of shrinking battle sprites."""
import json, concurrent.futures, urllib.request, urllib.error
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'game/pokemon-data.js').read_text(encoding='utf-8').split('=',1)[1].rstrip(';\n'))
dest=root/'game/assets/icons';dest.mkdir(parents=True,exist_ok=True)
base='https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-vii/icons/'
def fetch(dex):
    p=dest/f'{dex}.png'
    if p.exists():return dex
    try:raw=urllib.request.urlopen(base+f'{dex}.png',timeout=90).read()
    except urllib.error.HTTPError:return None
    if not raw.startswith(b'\x89PNG\r\n\x1a\n'):return None
    p.write_bytes(raw);return dex
dexes=sorted({s['dex'] for s in data['species'].values()})
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:ok=sorted(d for d in pool.map(fetch,dexes) if d)
(root/'game/pokemon-icons.js').write_text('/* Generated by scripts/collect-icons.py */\nwindow.POKEMON_ICONS=new Set('+json.dumps(ok,separators=(',',':'))+');\n',encoding='utf-8')
print('Menu icons:',len(ok),'of',len(dexes),'species')
