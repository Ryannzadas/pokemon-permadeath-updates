'use strict';
// Trainer sprites are animated PNGs (APNG). Phaser draws only the first frame of an image, so each
// one becomes a horizontal frame strip plus its frame durations, played as a Phaser animation.
const fs = require('node:fs'), path = require('node:path'), UPNG = require('upng-js');
const root = path.resolve(__dirname, '..'), source = path.join(root, 'game/assets/trainers'), out = path.join(source, 'sheets');
fs.mkdirSync(out, { recursive: true });
const manifest = {};
for (const file of fs.readdirSync(source).filter(f => f.endsWith('.png'))) {
  const bytes = fs.readFileSync(path.join(source, file));
  const img = UPNG.decode(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.length));
  const frames = UPNG.toRGBA8(img).map(f => new Uint8Array(f)), w = img.width, h = img.height;
  const strip = new Uint8Array(w * h * 4 * frames.length);
  frames.forEach((frame, i) => { for (let y = 0; y < h; y++) strip.set(frame.subarray(y * w * 4, (y + 1) * w * 4), (y * w * frames.length + i * w) * 4); });
  fs.writeFileSync(path.join(out, file), Buffer.from(UPNG.encode([strip.buffer], w * frames.length, h, 0)));
  // A 0 ms delay means "as fast as possible" in APNG; use the usual 100 ms instead.
  const delays = (img.frames.length ? img.frames : [{ delay: 100 }]).map(f => f.delay > 0 ? f.delay : 100);
  manifest[file.replace(/\.png$/, '')] = { frames: frames.length, width: w, height: h, delays };
}
fs.writeFileSync(path.join(root, 'game/trainer-anims.js'), '/* Generated by scripts/build-trainer-sheets.cjs */\nwindow.TRAINER_ANIMS=' + JSON.stringify(manifest) + ';\n');
console.log('Trainer animation sheets:', Object.keys(manifest).length);
