'use strict';
const assert=require('node:assert/strict');
const C=require('../game/camp/model.js');
const journey=()=>({battle:0,money:100,team:[{sp:'pikachu',hp:15,friendship:70},{sp:'eevee',hp:0,friendship:70}]});
const r=journey();
C.normalize(r);
assert.deepEqual(r.camp.position,C.spawn);
assert.equal(C.interact(r,1,'play').ok,false,'A dead Pokémon cannot interact');
assert.equal(C.interact(r,0,'invalid').ok,false);
assert.equal(C.interact(r,0,'play').gain,3);
assert.equal(C.interact(r,0,'feed').gain,5);
assert.equal(r.money,85);
assert.equal(C.interact(r,0,'play').gain,3);
const saturated=JSON.stringify(r);
assert.equal(C.interact(r,0,'feed').ok,false);
assert.equal(JSON.stringify(r),saturated,'A rejected interaction must not charge or change friendship');
C.normalize(r);assert.equal(r.camp.used,3,'Reopening the camp must not renew actions');
r.battle=1;C.normalize(r);assert.equal(r.camp.used,0);
r.money=14;assert.equal(C.interact(r,0,'feed').ok,false);assert.equal(r.camp.used,0);
r.team[0].friendship=254;assert.equal(C.interact(r,0,'play').gain,1);assert.equal(r.team[0].friendship,255);
assert.equal(C.interact(r,0,'play').ok,false);
r.camp.position={x:320,y:105,dir:'left'};assert.deepEqual(C.normalize(r).position,C.spawn,'Corrupt position inside tent returns to entrance');
assert.deepEqual(C.safePosition({x:NaN,y:12}),C.spawn);
assert.deepEqual(C.safePosition({x:100000,y:300}),C.spawn);
assert.equal(C.safePosition({x:320,y:294.6,dir:'up'}).y,294.6,'Saving against the log must not teleport the player');
const original=journey(),copy=JSON.parse(JSON.stringify(original));C.normalize(original);assert.deepEqual(original.team,copy.team);assert.equal(original.money,copy.money);
console.log('Camp model: 19 assertions passed.');
