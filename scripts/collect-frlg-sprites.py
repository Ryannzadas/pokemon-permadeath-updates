"""Download offline FireRed/LeafGreen battle sprites (front and back) from PokeAPI.
Only species #1-386 exist in those games; the others keep the regular sprite pack.
The manifest also records each sprite's empty rows at the bottom, so the battle scene can
rest every Pokémon on the ground the way the GBA games offset them per species."""
import json, struct, zlib, concurrent.futures, urllib.request
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'game/pokemon-data.js').read_text(encoding='utf-8').split('=',1)[1].rstrip(';\n'))
dest=root/'game/assets/sprites-frlg';dest.mkdir(parents=True,exist_ok=True)
base='https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-iii/firered-leafgreen/'
def fetch(job):
    dex,side=job;p=dest/f'{dex}-{side}.png'
    if p.exists():return
    raw=urllib.request.urlopen(base+('back/' if side=='b' else '')+f'{dex}.png',timeout=90).read()
    if not raw.startswith(b'\x89PNG\r\n\x1a\n'):raise ValueError(dex)
    p.write_bytes(raw)

def bottom_padding(path):
    """Empty (fully transparent) rows at the bottom of a non-interlaced PNG."""
    raw=path.read_bytes();pos=8;idat=b'';trns=None
    while pos<len(raw):
        size,kind=struct.unpack('>I4s',raw[pos:pos+8]);body=raw[pos+8:pos+8+size];pos+=12+size
        if kind==b'IHDR':w,h,depth,color,_,_,interlace=struct.unpack('>IIBBBBB',body)
        elif kind==b'tRNS':trns=body
        elif kind==b'IDAT':idat+=body
    if interlace:raise ValueError(f'{path.name}: interlaced PNG')
    channels={0:1,2:3,3:1,4:2,6:4}[color];bpp=max(1,channels*depth//8);stride=(w*channels*depth+7)//8
    data=zlib.decompress(idat);rows=[];prev=bytearray(stride);i=0
    for _ in range(h):
        f=data[i];line=bytearray(data[i+1:i+1+stride]);i+=1+stride
        for x in range(stride):
            a=line[x-bpp] if x>=bpp else 0;b=prev[x];c=prev[x-bpp] if x>=bpp else 0
            if f==1:line[x]=(line[x]+a)&255
            elif f==2:line[x]=(line[x]+b)&255
            elif f==3:line[x]=(line[x]+(a+b)//2)&255
            elif f==4:
                pa,pb,pc=abs(b-c),abs(a-c),abs(a+b-2*c)
                line[x]=(line[x]+(a if pa<=pb and pa<=pc else b if pb<=pc else c))&255
        rows.append(line);prev=line
    def opaque(line,x):
        if color==6:return line[x*4+3]>0
        if color==4:return line[x*2+1]>0
        if color==3:
            bit=x*depth;v=(line[bit//8]>>(8-depth-bit%8))&((1<<depth)-1)
            return trns is None or v>=len(trns) or trns[v]>0
        return True
    for pad,line in enumerate(reversed(rows)):
        if any(opaque(line,x) for x in range(w)):return pad
    return h

dexes=sorted({s['dex'] for s in data['species'].values() if s['dex']<=386})
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:list(pool.map(fetch,[(d,s) for d in dexes for s in ('f','b')]))
# Manifest read by the battle presentation: {dex:[front bottom padding, back bottom padding]} in sprite pixels.
manifest={d:[bottom_padding(dest/f'{d}-f.png'),bottom_padding(dest/f'{d}-b.png')] for d in dexes if (dest/f'{d}-f.png').exists() and (dest/f'{d}-b.png').exists()}
(root/'game/frlg-sprites.js').write_text('/* Generated by scripts/collect-frlg-sprites.py */\nwindow.FRLG_SPRITES='+json.dumps(manifest,separators=(',',':'))+';\n',encoding='utf-8')
print('FireRed/LeafGreen sprites:',len(manifest),'species')
